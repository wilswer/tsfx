"""Parity tests against tsfresh's own feature calculator test cases.

Input/expected pairs are copied from tsfresh v0.21.2,
tests/units/feature_extraction/test_feature_calculations.py
(https://github.com/blue-yonder/tsfresh), used under the MIT licence
(full text in TSFRESH_LICENSE next to this file):

    Copyright (c) 2016 Maximilian Christ, Blue Yonder GmbH

Cases tsfresh runs on an empty series are left out: TSFX computes features
per group, and a group cannot be empty.

Where tsfresh's own tests cannot tell two behaviours apart, cases are
generated by running the tsfresh calculators (marked "generated" and stating
the tsfresh / numpy / pandas versions used).

Parity rule: tsfresh is the specification, and any difference is a bug, with
one exception. If tsfresh's result comes from an accident of its arithmetic
rather than from defined behaviour (its own, or numpy's / pandas' documented
semantics such as NaN propagation or comparisons with NaN being False), TSFX
keeps the meaningful result instead. Each such deliberate deviation has a test
whose name ends in ``_deviation`` and is described in the feature's docstring.
Current deviations:

- ``sample_entropy`` with +-inf in the series
- ``sum_of_reoccurring_values`` / ``sum_of_reoccurring_data_points`` with a
  NaN or +-inf that occurs only once
- ``query_similarity_count`` of a series shorter than the query (tsfresh
  raises; TSFX gives NaN)
- ``fft_coefficient`` with a NaN or +-inf in the series

Cases that still fail are marked with ``_bug`` (strict xfail), so the marker
must be removed once the fix lands.
"""

import math

import polars as pl
import pytest
from tsfx import ExtractionSettings, FeatureSetting, extract_features

CONFIG_PATH = "./python_tests/data/.tsfx-config-tsfresh-parity.toml"


def _bug(*case: object, reason: str):
    """Mark a parity case that fails because of a known TSFX bug."""
    return pytest.param(
        *case,
        marks=pytest.mark.xfail(strict=True, reason=f"parity bug: {reason}"),
    )


def _features(values: list[float]) -> dict:
    """Extract the parity features for a single series."""
    df = pl.DataFrame(
        {"id": ["a"] * len(values), "val": [float(v) for v in values]},
    ).lazy()
    opts = ExtractionSettings(
        grouping_cols=["id"],
        feature_setting=FeatureSetting.Comprehensive,
        value_cols=["val"],
        config_path=CONFIG_PATH,
    )
    fdf = extract_features(df, opts)
    assert fdf.shape[0] == 1
    return fdf.row(0, named=True)


def _assert_feature(
    values: list[float],
    column: str,
    expected: float,
    abs_tol: float = 1e-7,
) -> None:
    features = _features(values)
    assert column in features, f"column {column!r} not extracted"
    result = features[column]
    if math.isnan(expected):
        assert result is not None and math.isnan(result), result
    else:
        # tsfresh uses assertEqual / assertAlmostEqual (7 decimal places
        # unless a test says otherwise)
        assert result == pytest.approx(expected, abs=abs_tol)


